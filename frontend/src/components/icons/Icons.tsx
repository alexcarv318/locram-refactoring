import * as React from "react"

export type IconProps = React.SVGProps<SVGSVGElement> & {
    title?: string
    size?: number | string
}

function createIcon(paths: React.ReactNode, viewBox = "0 0 20 20", defaultAriaHidden = true) {
    const Icon = React.forwardRef<SVGSVGElement, IconProps>(({ title, size = "1em", className, ...rest }, ref) => {
        const ariaHidden = title ? undefined : defaultAriaHidden
        return (
            <svg
                ref={ref}
                xmlns="http://www.w3.org/2000/svg"
                viewBox={viewBox}
                width={size}
                height={size}
                fill="none"
                role={title ? "img" : "presentation"}
                aria-hidden={ariaHidden as any}
                aria-label={title}
                className={className}
                {...rest}
            >
                {title ? <title>{title}</title> : null}
                <g vectorEffect="non-scaling-stroke">{paths}</g>
            </svg>
        )
    })
    Icon.displayName = "Icon"
    return Icon
}

